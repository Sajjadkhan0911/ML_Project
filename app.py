# -----------------------------------------------------------------------------
# 3. INTERFACE HEADER & APP ENTRY POINT
# -----------------------------------------------------------------------------
st.markdown("# 🩺 Chronic Kidney Disease Predictive Intelligence Workspace")
st.markdown("Enter client clinical test measurements below to trigger prediction scoring via the RFE Optimized Ensemble Model.")
st.write("---")

if model is None or scaler is None or selected_features is None:
    st.error("Application setup broken. Ensure standard `.pkl` dependencies reside in runtime root directory.")
else:
    # Segment layout visually by test groups
    col1, col2 = st.columns(2)
    
    raw_user_inputs = {}
    
    # Dynamically separate features between Column 1 and Column 2
    for idx, feat_id in enumerate(selected_features):
        target_col = col1 if (idx % 2 == 0) else col2
        meta = FEATURE_DETAILS[feat_id]
        
        with target_col:
            if meta['type'] == 'num':
                # Preserve floating point variations based on typical values
                step_val = 0.1 if isinstance(meta['default'], float) else 1
                raw_user_inputs[feat_id] = st.number_input(
                    label=meta['label'],
                    min_value=float(meta['min']),
                    max_value=float(meta['max']),
                    value=float(meta['default']),
                    step=float(step_val),
                    key=f"input_{feat_id}"
                )
            elif meta['type'] == 'cat':
                raw_user_inputs[feat_id] = st.selectbox(
                    label=meta['label'],
                    options=meta['options'],
                    index=0,
                    key=f"input_{feat_id}"
                )

    st.write("---")
    
    # -----------------------------------------------------------------------------
    # 4. PREDICTION ENGINE PIPELINE
    # -----------------------------------------------------------------------------
    if st.button("Execute Predictive Diagnosis", type="primary", use_container_width=True):
        
        # Step A: Convert inputs into raw data list ordered exactly by the full 24 feature array
        full_features_list = [
            'age', 'bp', 'sg', 'al', 'su', 'rbc', 'pc', 'pcc', 'ba', 'bgr', 'bu', 
            'sc', 'sod', 'pot', 'hemo', 'pcv', 'wbcc', 'rbcc', 'htn', 'dm', 'cad', 
            'appet', 'pe', 'ane'
        ]
        
        processed_row = []
        for feat in full_features_list:
            # Fallback for missing input data if it isn't used by RFE
            current_val = raw_user_inputs.get(feat, FEATURE_DETAILS[feat].get('default', 'missing'))
            
            # Map Categorical selections using encoded mappings
            if FEATURE_DETAILS[feat]['type'] == 'cat':
                val_str = str(current_val)
                mapping_dict = CATEGORICAL_MAPPINGS.get(feat, {})
                encoded_val = mapping_dict.get(val_str, mapping_dict.get('missing', 0))
                processed_row.append(encoded_val)
            else:
                processed_row.append(float(current_val))
                
        # Prepare matrix for transform scaler
        full_sample_matrix = np.array([processed_row])
        
        # Step B: Scale the complete sample
        scaled_sample_matrix = scaler.transform(full_sample_matrix)
        
        # Step C: Extract RFE Masked Columns
        # Generate bool index mask matching names
        rfe_mask = [f_name in selected_features for f_name in full_features_list]
        final_input_vector = scaled_sample_matrix[:, rfe_mask]
        
        # Step D: Infer results
        prediction_class = model.predict(final_input_vector)[0]
        prediction_probability = model.predict_proba(final_input_vector)[0][1]
        
        # -----------------------------------------------------------------------------
        # 5. UI RESULTS OUTPUT
        # -----------------------------------------------------------------------------
        st.subheader("Diagnostic Results Dashboard")
        
        if prediction_class == 1:
            st.markdown(f"""
                <div class="metric-card positive">
                    <h3>⚠️ Chronic Kidney Disease Detected</h3>
                    <p>The RFE Optimized Ensemble Engine calculates a high likelihood of structural anomalies.</p>
                    <h2 style="color: #e74c3c; margin-top: 5px;">Probability Index: {prediction_probability * 100:.2f}%</h2>
                </div>
            """, unsafe_allow_html=True)
        else:
            st.markdown(f"""
                <div class="metric-card negative">
                    <h3>✅ No Signs of Chronic Kidney Disease Detected</h3>
                    <p>Measurements align closely within base thresholds of non-chronic baseline metrics.</p>
                    <h2 style="color: #2ecc71; margin-top: 5px;">Probability Index: {(1 - prediction_probability) * 100:.2f}%</h2>
                </div>
            """, unsafe_allow_html=True)
            
        # Optional: Print raw input configurations vector for diagnostic debug monitoring
        with st.expander("Show Scaled Pipeline Debug Vectors"):
            st.write("Processed Sample (Original Scale Array Structure):", processed_row)
            st.write("Final Scaled RFE Feature Input array passed to model:", final_input_vector)
