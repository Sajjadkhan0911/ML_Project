@st.cache_resource
def load_ml_artifacts():
    """Loads the model, scale factor, and selected feature lists."""
    try:
        # Load the RFE Optimized Model
        with open('best_ckd_model_rfe.pkl', 'rb') as f:
            model = pickle.load(f)
        
        # Load Scaler (Handles both 'scaler.pkl' or your local copy 'scaler (2).pkl')
        try:
            with open('scaler.pkl', 'rb') as f:
                scaler = pickle.load(f)
        except FileNotFoundError:
            with open('scaler (2).pkl', 'rb') as f:
                scaler = pickle.load(f)

        # Load Selected Feature Names
        with open('feature_names_rfe.pkl', 'rb') as f:
            features = pickle.load(f)
            
        return model, scaler, features
    except Exception as e:
        st.error(f"Error loading artifact dependencies: {e}")
        return None, None, None

